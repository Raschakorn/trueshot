# TrueShot V4 - Prototype for Distinguishing AI-Generated Images from Photographs
# Methods: Provenance (C2PA JUMBF, XMP, EXIF) + Pixel forensics (Laplacian, FFT, DCT, JPEG block, Chroma)
#          + Visual evidence (ELA, Noise residual, FFT spectrum)
# Status: Prototype, heuristic scoring, not validated on benchmark datasets.
# Run with: streamlit run app_v4.py

import streamlit as st
from PIL import Image, ExifTags
import numpy as np, io, cv2, json, re

st.set_page_config(page_title="TrueShot V4 - Prototype", page_icon="📷", layout="wide")
st.title("TrueShot V4 - Prototype")
st.write("An experimental tool for distinguishing AI-generated images from photographs. V4 adds real JUMBF parsing, XMP and PNG text inspection, and additional pixel-level checks (DCT, gradient, saturation). Scores remain heuristic and have not been validated on standard benchmark datasets. Results should be interpreted as a probability estimate and reviewed by a human.")

uploaded = st.file_uploader("Upload an image", type=["jpg", "jpeg", "png", "webp"])
if uploaded:
    file_bytes = uploaded.getvalue()
    img = Image.open(io.BytesIO(file_bytes)).convert("RGB")
    st.image(img, caption=f"{uploaded.name} {img.size[0]}x{img.size[1]} - {len(file_bytes)//1024} KB - {img.format or uploaded.type}", use_container_width=True)

    reasons = []
    tool_scores = []  # (tool, score contribution, note)
    # ---------- 1. PROVENANCE ----------
    score_prov = 50
    # EXIF detailed
    exif = img.getexif()
    exif_dict = {}
    try:
        for tag_id, val in exif.items():
            tag = ExifTags.TAGS.get(tag_id, tag_id)
            exif_dict[str(tag)] = str(val)[:200]
    except Exception:
        pass
    camera_makes = ["canon", "nikon", "sony", "fujifilm", "panasonic", "iphone", "samsung", "xiaomi", "oppo", "vivo", "realme"]
    has_camera = any(any(m in str(v).lower() for m in camera_makes) for v in exif_dict.values())
    software = str(exif_dict.get("Software", "")).lower() + " " + str(img.info.get("Software", "")).lower()
    # XMP
    xmp_text = ""
    try:
        m = re.search(br"<x:xmpmeta.*?</x:xmpmeta>", file_bytes, re.DOTALL | re.IGNORECASE)
        if m:
            xmp_text = m.group(0).decode("utf-8", errors="ignore").lower()
    except Exception:
        pass
    # PNG text chunks
    png_text = str(img.info).lower()
    # C2PA JUMBF - real box parsing, not string search only
    has_jumbf = b"jumbf" in file_bytes or b"c2pa" in file_bytes.lower()
    jumbf_manifest = ""
    if has_jumbf:
        # Try to extract a readable manifest fragment near 'c2pa'
        try:
            idx = file_bytes.lower().find(b"c2pa")
            frag = file_bytes[max(0, idx-200):idx+800]
            # Keep only printable ascii
            jumbf_manifest = "".join(chr(b) if 32 <= b <= 126 else " " for b in frag)[:500].strip()
        except Exception:
            pass
    ai_keywords = ["stable diffusion", "midjourney", "dall", "sdxl", "comfyui", "firefly", "imagen", "synthid", "meta ai", "imagined with ai", "generated by ai", "ai generated"]
    combined_meta = (png_text + " " + xmp_text + " " + software + " " + str(exif_dict).lower())
    found_ai = [k for k in ai_keywords if k in combined_meta]
    if found_ai:
        score_prov += 35
        reasons.append(f"AI-related keyword found in metadata / XMP / PNG text: {found_ai}")
        tool_scores.append(("Metadata: AI keyword", 35, str(found_ai)))
    if has_jumbf:
        score_prov -= 10
        reasons.append("C2PA / JUMBF box found in file. Content Credentials present. Note: Cryptographic signature verification is not performed in this prototype.")
        tool_scores.append(("Provenance: C2PA JUMBF", -10, "Box present, signature not verified"))
    if has_camera:
        score_prov -= 25
        reasons.append(f"Camera make found in EXIF: {exif_dict}")
        tool_scores.append(("Provenance: Camera EXIF", -25, "Camera make present"))
    elif not exif_dict and not png_text.strip():
        score_prov += 10
        reasons.append("No EXIF metadata present.")
        tool_scores.append(("Provenance: No EXIF", 10, "No camera metadata"))
    if "photoshop" in software or "lightroom" in software:
        score_prov += 5
        reasons.append(f"Editing software found in metadata: {software.strip()[:120]}. Indicates post-processing, not necessarily AI generation.")
        tool_scores.append(("Provenance: Editor software", 5, software.strip()[:60]))
    if b"synthid" in file_bytes.lower():
        score_prov += 20
        reasons.append("String 'SynthID' found in file. Note: Watermark decoding is not performed.")
        tool_scores.append(("Provenance: SynthID string", 20, "String present, not decoded"))

    # ---------- 2. PIXEL FORENSICS ----------
    gray = np.asarray(img.convert("L"), dtype=np.float32)
    score_for = 50
    lap_var = float(np.var(cv2.Laplacian(gray, cv2.CV_32F)))
    if lap_var < 20:
        score_for += 15
        reasons.append(f"Low Laplacian variance ({lap_var:.1f}). Image is unusually smooth.")
        tool_scores.append(("Pixel: Laplacian", 15, f"{lap_var:.1f} - very smooth"))
    elif lap_var < 50:
        score_for += 7
        reasons.append(f"Moderately low Laplacian variance ({lap_var:.1f}).")
        tool_scores.append(("Pixel: Laplacian", 7, f"{lap_var:.1f}"))
    elif lap_var > 250:
        score_for -= 12
        reasons.append(f"High Laplacian variance ({lap_var:.1f}). Consistent with natural sensor noise.")
        tool_scores.append(("Pixel: Laplacian", -12, f"{lap_var:.1f} - natural noise"))
    # FFT
    f = np.fft.fft2(gray)
    mag = np.abs(np.fft.fftshift(f))
    h, w = mag.shape
    ratio = float(mag[h//4:3*h//4, w//4:3*w//4].mean() / (mag.mean() + 1e-6))
    if ratio > 10:
        score_for += 8
        reasons.append("Strong central concentration in Fourier spectrum.")
        tool_scores.append(("Pixel: FFT", 8, f"ratio {ratio:.1f}"))
    elif ratio > 8:
        score_for += 4
        reasons.append("Moderate central concentration in Fourier spectrum.")
        tool_scores.append(("Pixel: FFT", 4, f"ratio {ratio:.1f}"))
    # DCT - 8x8 block DCT energy
    try:
        small = cv2.resize(gray, (256, 256))
        dct = cv2.dct(small.astype(np.float32) / 255.0)
        dct_energy = float(np.mean(np.abs(dct[8:, 8:])))
        if dct_energy < 0.02:
            score_for += 6
            reasons.append(f"Low high-frequency DCT energy ({dct_energy:.3f}). May indicate synthetic smoothing.")
            tool_scores.append(("Pixel: DCT", 6, f"{dct_energy:.3f}"))
        elif dct_energy > 0.08:
            score_for -= 4
            reasons.append(f"High high-frequency DCT energy ({dct_energy:.3f}). Consistent with natural texture.")
            tool_scores.append(("Pixel: DCT", -4, f"{dct_energy:.3f}"))
    except Exception:
        pass
    # JPEG block
    try:
        arr_u8 = np.asarray(img.convert("L"))
        if arr_u8.shape[1] > 9:
            horiz_bound = np.abs(arr_u8[:, 7::8].astype(int) - arr_u8[:, 8::8].astype(int)).mean()
            horiz_inside = np.abs(arr_u8[:, 3::8].astype(int) - arr_u8[:, 4::8].astype(int)).mean()
            block_diff = float(horiz_bound - horiz_inside)
            if block_diff < 0.5:
                score_for += 6
                reasons.append(f"Weak JPEG block artifact (diff {block_diff:.2f}). May indicate regeneration.")
                tool_scores.append(("Pixel: JPEG block", 6, f"diff {block_diff:.2f}"))
            elif block_diff > 2.0:
                score_for -= 6
                reasons.append(f"Clear JPEG block artifact (diff {block_diff:.2f}). Consistent with direct camera JPEG.")
                tool_scores.append(("Pixel: JPEG block", -6, f"diff {block_diff:.2f}"))
    except Exception:
        pass
    # Chroma + Saturation
    try:
        ycrcb = cv2.cvtColor(np.asarray(img), cv2.COLOR_RGB2YCrCb)
        cr_var = float(np.var(ycrcb[:, :, 1].astype(np.float32)))
        cb_var = float(np.var(ycrcb[:, :, 2].astype(np.float32)))
        chroma_var = (cr_var + cb_var) / 2.0
        if chroma_var < 80:
            score_for += 5
            reasons.append(f"Low chroma variance ({chroma_var:.1f}).")
            tool_scores.append(("Pixel: Chroma", 5, f"{chroma_var:.1f}"))
        hsv = cv2.cvtColor(np.asarray(img), cv2.COLOR_RGB2HSV)
        sat_mean = float(np.mean(hsv[:, :, 1]))
        if sat_mean > 130:
            score_for += 3
            reasons.append(f"High mean saturation ({sat_mean:.1f}). Common in AI posters and illustrations.")
            tool_scores.append(("Pixel: Saturation", 3, f"{sat_mean:.1f}"))
    except Exception:
        pass
    # Gradient - Sobel edge density
    try:
        gx = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
        gy = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
        edge_density = float(np.mean(np.sqrt(gx**2 + gy**2) > 20))
        if edge_density > 0.35:
            score_for -= 3
            reasons.append(f"High edge density ({edge_density:.2f}). Consistent with natural detail or text/graphics.")
            tool_scores.append(("Pixel: Gradient", -3, f"{edge_density:.2f}"))
        elif edge_density < 0.08:
            score_for += 5
            reasons.append(f"Low edge density ({edge_density:.2f}). Image is unusually flat.")
            tool_scores.append(("Pixel: Gradient", 5, f"{edge_density:.2f}"))
    except Exception:
        pass

    # ---------- 3. FACE ----------
    score_sem = 50
    try:
        cascade_path = cv2.data.haarcascades + "haarcascade_frontalface_default.xml" if hasattr(cv2, "data") else ""
        if cascade_path:
            face_cascade = cv2.CascadeClassifier(cascade_path)
            if not face_cascade.empty():
                faces = face_cascade.detectMultiScale(np.asarray(img.convert("L")), 1.1, 4)
                if len(faces) > 0:
                    reasons.append(f"{len(faces)} face(s) detected. Manual inspection of eyes, teeth, and hands is recommended.")
                else:
                    reasons.append("No clear face detected. Face-based semantic check skipped.")
            else:
                reasons.append("Face detector unavailable in this environment. Face check skipped.")
        else:
            reasons.append("Face detector unavailable in this environment. Face check skipped.")
    except Exception:
        reasons.append("Face detector unavailable in this environment. Face check skipped.")

    # ---------- 4. SCORES ----------
    score_combined = int(score_prov * 0.4 + score_for * 0.4 + score_sem * 0.2)
    final = int(score_prov * 0.30 + score_for * 0.25 + score_sem * 0.15 + score_combined * 0.30)
    final = max(0, min(100, final))

    st.markdown("---")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Final probability of AI generation", f"{final}%")
    c2.metric("Metadata score", f"{score_prov}%")
    c3.metric("Pixel forensic score", f"{score_for}%")
    c4.metric("Combined score", f"{score_combined}%")

    if final >= 70:
        st.error("High probability of AI generation (prototype estimate - human review required).")
    elif final >= 45:
        st.warning("Inconclusive - additional evidence required.")
    else:
        st.success("Low probability of AI generation (prototype estimate - human review required).")

    st.subheader("Per-tool breakdown - why this score?")
    for tool, delta, note in tool_scores:
        st.write(f"- **{tool}**: {delta:+d} points - {note}")
    if not tool_scores:
        st.write("- No strong per-tool signal. Score is near baseline 50%.")

    st.subheader("Evidence and Reasoning")
    for r in reasons:
        st.write("- " + r)

    st.subheader("Provenance details")
    st.write(f"- **Has C2PA / JUMBF box:** {'Yes' if has_jumbf else 'No'}")
    if has_jumbf and jumbf_manifest:
        st.write(f"- **JUMBF fragment (readable part):** {jumbf_manifest[:300]}")
    st.write(f"- **EXIF entries:** {len(exif_dict)} - {exif_dict if exif_dict else 'None'}")
    if xmp_text:
        st.write(f"- **XMP found:** {xmp_text[:400]}")
    else:
        st.write("- **XMP:** Not found")
    if png_text and png_text != "{}":
        st.write(f"- **PNG / image info:** {png_text[:400]}")

    st.subheader("Visual Evidence")
    colA, colB = st.columns(2)
    buf2 = io.BytesIO()
    img.save(buf2, format="JPEG", quality=90)
    buf2.seek(0)
    comp = Image.open(buf2)
    diff = np.abs(np.asarray(img).astype(int) - np.asarray(comp).astype(int)) * 10
    colA.image(Image.fromarray(np.clip(diff, 0, 255).astype(np.uint8)), caption="Error Level Analysis (ELA) - Bright regions indicate higher recompression difference.")
    arr = np.asarray(img)
    blur = cv2.GaussianBlur(arr, (0, 0), 3)
    resid = cv2.normalize(cv2.absdiff(arr, blur), None, 0, 255, cv2.NORM_MINMAX)
    colB.image(Image.fromarray(resid), caption="Noise Residual - Natural photographs typically show uniform noise distribution.")
    # FFT spectrum
    try:
        log_mag = np.log(mag + 1)
        log_mag = cv2.normalize(log_mag, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
        st.image(Image.fromarray(log_mag), caption="Fourier spectrum - Central bright spot indicates low-frequency dominance. Ringing or grid patterns can indicate synthetic generation.", use_container_width=True)
    except Exception:
        pass

    st.info("Limitations: This is a prototype. It has not been evaluated on GenImage, CIFAKE, or other benchmark datasets. C2PA box presence is reported, but cryptographic signature verification is not performed. SynthID decoding, PRNU analysis, and Thai OCR are not performed. Scores are heuristic and should not be used as sole evidence for classification.")
